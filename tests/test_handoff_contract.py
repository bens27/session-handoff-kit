"""Wire bytes captured and validated against 5f8c080 before the contract migration.

Fixtures are historical output, not generated by the implementation under test.
The renderer seam also covers projection that cannot be exercised without a
stateful transfer; lifecycle tests continue to own transfer/authorization rules.
"""
import contextlib
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
HOOKS = ROOT / 'skills/session-handoff/hooks'
sys.path.insert(0, str(HOOKS))
import handoff_contract as contract
import context_watch
import handoff_protocol

WIRE = json.loads((ROOT / 'tests/fixtures/contract/wire.json').read_text())


class ContractTests(unittest.TestCase):
    def test_opening_prose_preserves_timestamps_age_notice_and_commands(self):
        for case in WIRE['opening']:
            with self.subTest(prompt=case['args'][0]):
                actual = handoff_protocol.opening_action(*case['args'])
                self.assertEqual(actual.replace(str(HOOKS), '<HOOKS>'), case['stdout'])

    def test_exit_status_preserves_each_surface_policy(self):
        failures = {
            'protocol': {'error', 'blocked', 'invalid', 'conflict', 'needs-context',
                         'needs-original-draft', 'verification-failed',
                         'verification-timeout', 'timeout', 'needs-confirmation'},
            'report': {'unavailable'},
            'dispatch': {'blocked'},
        }
        outcomes = set().union(*failures.values(), {
            'saved', 'incomplete', 'resumed', 'ready', 'prepared', 'retrieved',
            'proceed', 'ask', 'none', 'available', 'unknown', '', None,
        })
        for surface, rejected in failures.items():
            for outcome in outcomes:
                with self.subTest(surface=surface, outcome=outcome):
                    self.assertEqual(contract.exit_status(surface, outcome),
                                     1 if outcome in rejected else 0)
        for operation in ('save', 'resume', None):
            with self.subTest(operation=operation):
                self.assertEqual(contract.exit_status('protocol', 'incomplete', operation),
                                 1 if operation == 'save' else 0)
        for operation, success in (('adopt', 'resumed'), ('restart', 'ready')):
            for outcome in outcomes:
                with self.subTest(operation=operation, outcome=outcome):
                    self.assertEqual(contract.exit_status('preflight', outcome, operation),
                                     0 if outcome == success else 1)
        # Other preflight operations historically return 0 for normal results.
        for operation in ('preflight', 'status', 'refusal', 'successor', 'acceptance'):
            for outcome in outcomes:
                with self.subTest(operation=operation, outcome=outcome):
                    self.assertEqual(contract.exit_status('preflight', outcome, operation), 0)

    def test_renderer_preserves_existing_bytes_and_required_delivery(self):
        for case in WIRE['render']:
            with self.subTest(profile=case['profile'], fields=case['fields'], pretty=case['pretty']):
                output = io.StringIO()
                with contextlib.redirect_stdout(output):
                    contract.emit_output(case['value'], profile=case['profile'],
                                         fields=case['fields'], pretty=case['pretty'])
                self.assertEqual(output.getvalue(), case['stdout'])

    def test_public_cli_bytes_streams_and_exit_status(self):
        with tempfile.TemporaryDirectory() as temp:
            env = {k: v for k, v in os.environ.items() if not k.startswith(
                ('HANDOFF_', 'CONTEXT_WATCH_', 'AGENTSROOM_', 'CODEX_', 'CLAUDE_', 'TMUX'))}
            env.update(HOME=temp, HANDOFF_STATE_DIR=temp, HANDOFF_TELEMETRY='0')
            for case in WIRE['cli'] + json.loads((ROOT / 'tests/fixtures/contract/legacy.json').read_text()):
                with self.subTest(args=case['args']):
                    p = subprocess.run([sys.executable, str(HOOKS / case['script']), *case['args']],
                                       input=case['input'], text=True, capture_output=True,
                                       cwd=temp, env=env, timeout=30)
                    self.assertEqual((p.stdout, p.stderr, p.returncode),
                                     (case['stdout'], case['stderr'], case['code']))

    def test_cli_router_preserves_help_output(self):
        import handoff_cli
        import handoff_ledger
        fixture = json.loads((ROOT / 'tests/fixtures/contract/legacy.json').read_text())[0]
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            code = handoff_cli.cli([], handoff_ledger)
        self.assertEqual((output.getvalue(), code), (fixture['stdout'], fixture['code']))

    def test_hook_envelopes_and_plain_text_remain_exact(self):
        for case in WIRE['hook']:
            with self.subTest(agent=case['agent'], event=case['event'], mode=case['mode']):
                output = io.StringIO()
                with contextlib.redirect_stdout(output), self.assertRaises(SystemExit) as stopped:
                    context_watch.emit(case['agent'], case['event'], 'Résumé "quoted"\nnext', case['mode'])
                self.assertEqual((output.getvalue(), stopped.exception.code),
                                 (case['stdout'], case['code']))


class CommandContractTests(unittest.TestCase):
    def test_commands_match_captured_shell_bytes(self):
        cases = json.loads((ROOT / 'tests/fixtures/contract/commands.json').read_text())
        for case in cases:
            with self.subTest(case=case):
                if case['kind'] == 'ledger':
                    actual = contract.ledger_command(os.path.dirname(case['script']), *case['args'])
                elif case['kind'] == 'adopt':
                    actual = contract.adopt_command(case['script'], case['root'], case['request'])
                else:
                    actual = contract.handle_command(case['script'], case['handle'])
                self.assertEqual(actual, case['command'])


class DispatchContractTests(unittest.TestCase):
    def test_dispatch_schema_and_authorization_match_landed_fix(self):
        fixture = json.loads((ROOT / 'tests/fixtures/contract/dispatch.json').read_text())
        for case in fixture['cases']:
            with self.subTest(code=case['code']):
                result = contract.dispatch_result(case['outcome'], case['code'],
                                                  case['request'], **case['extra'])
                self.assertEqual(contract.render_output(result) + '\n', case['stdout'])

    def test_closed_code_set_and_retry_policy(self):
        fixture = json.loads((ROOT / 'tests/fixtures/contract/dispatch.json').read_text())
        self.assertEqual(contract.DISPATCH_CODES, fixture['codes'])
        for code, retryable in fixture['codes'].items():
            with self.subTest(code=code):
                result = contract.dispatch_result('blocked', code, {})
                self.assertEqual(result['retryable'], retryable)
                if retryable:
                    self.assertEqual(result['retry'], dict(max_attempts=3, backoff_seconds=[1, 4, 16], same_request=True))
                else:
                    self.assertNotIn('retry', result)
        with self.assertRaises(KeyError):
            contract.dispatch_result('blocked', 'not-a-code', {})
